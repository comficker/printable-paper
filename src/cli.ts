#!/usr/bin/env node
/**
 * printable-paper CLI.
 *
 *   npx printable-paper graph --size a4 --spacing 5mm --out grid.pdf
 *   npx printable-paper isometric --size letter --format svg
 *   npx printable-paper list types
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  PAPER_SIZES,
  PAPER_TYPE_OPTIONS,
  SPACING_OPTIONS,
  LINE_COLORS,
  MARGINS,
  THICKNESS,
  renderPaperSvg,
  type LineColorId,
  type MarginId,
  type Orientation,
  type PaperConfig,
  type PaperSizeId,
  type PaperType,
  type ThicknessId,
} from './index.js'
import { renderPaperPdf } from './index.js'

const SITE = 'https://freegraphpaper.net'

/** data/ ships beside dist/, so it can also be read straight out of node_modules. */
const PKG_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

interface PaperTypeRow {
  id: string
  name: string
  description: string
  freeGraphPaper: string
}

function paperTypes(): PaperTypeRow[] {
  return JSON.parse(readFileSync(join(PKG_ROOT, 'data', 'paper-types.json'), 'utf8'))
}

function usage(): string {
  return `printable-paper - generate printable ruled paper as SVG or PDF

Usage
  printable-paper <type> [options]
  printable-paper list types|sizes|spacings

Options
  --size <id>        page size (default a4)
  --orientation <o>  portrait | landscape (default portrait)
  --spacing <v>      grid spacing: an id such as 5mm, quarter-inch, or a number in mm
  --margin <m>       none | small | medium | large (default small)
  --color <c>        ${Object.keys(LINE_COLORS).join(' | ')} (default light)
  --thickness <t>    ${Object.keys(THICKNESS).join(' | ')} (default thin)
  --pages <n>        PDF only, 1-50 identical sheets (default 1)
  --format <f>       pdf | svg (default taken from --out, else pdf)
  --out <file>       output path (default paper.<format>; "-" writes to stdout)

Examples
  printable-paper graph --size letter --spacing quarter-inch --out quarter-inch-grid.pdf
  printable-paper dot --spacing 5mm --format svg --out dots.svg
  printable-paper coordinate --size a4 --margin medium --out axes.pdf

Every sheet is generated by the same geometry engine as ${SITE},
where the same papers can be previewed and downloaded in a browser.`
}

function parseArgs(argv: string[]): { positional: string[]; flags: Record<string, string> } {
  const positional: string[] = []
  const flags: Record<string, string> = {}
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]!
    if (arg.startsWith('--')) {
      const [key, inline] = arg.slice(2).split('=')
      if (inline !== undefined) flags[key!] = inline
      else if (argv[i + 1] && !argv[i + 1]!.startsWith('--')) flags[key!] = argv[++i]!
      else flags[key!] = 'true'
    } else {
      positional.push(arg)
    }
  }
  return { positional, flags }
}

function fail(message: string): never {
  console.error(`printable-paper: ${message}`)
  process.exit(1)
}

function resolveSpacing(value: string | undefined, fallback: number): number {
  if (!value) return fallback
  const preset = SPACING_OPTIONS.find((s) => s.id === value)
  if (preset) return preset.mm
  const mm = Number(value.replace(/mm$/i, ''))
  if (Number.isFinite(mm) && mm > 0) return mm
  fail(`unknown spacing "${value}". Try one of: ${SPACING_OPTIONS.map((s) => s.id).join(', ')}`)
}

function list(what: string | undefined): void {
  if (what === 'sizes') {
    for (const [id, s] of Object.entries(PAPER_SIZES)) {
      console.log(`${id.padEnd(14)} ${s.label.padEnd(20)} ${s.w} x ${s.h} mm`)
    }
    return
  }
  if (what === 'spacings') {
    for (const s of SPACING_OPTIONS) console.log(`${s.id.padEnd(14)} ${s.label.padEnd(10)} ${s.mm.toFixed(3)} mm`)
    return
  }
  for (const t of paperTypes()) {
    console.log(`${t.id.padEnd(14)} ${t.name.padEnd(26)} ${t.freeGraphPaper}`)
  }
}

function main(): void {
  const { positional, flags } = parseArgs(process.argv.slice(2))
  const command = positional[0]

  if (!command || flags.help || command === 'help') {
    console.log(usage())
    return
  }
  if (command === 'list') return list(positional[1])

  const types = PAPER_TYPE_OPTIONS.map((t) => t.id)
  if (!types.includes(command as PaperType)) {
    fail(`unknown paper type "${command}". Run "printable-paper list types" to see all ${types.length}.`)
  }

  const size = (flags.size ?? 'a4') as PaperSizeId
  if (!(size in PAPER_SIZES)) {
    fail(`unknown size "${size}". Run "printable-paper list sizes" to see all.`)
  }
  const margin = (flags.margin ?? 'small') as MarginId
  if (!(margin in MARGINS)) fail(`unknown margin "${margin}"`)
  const color = (flags.color ?? 'light') as LineColorId
  if (!(color in LINE_COLORS)) fail(`unknown color "${color}"`)
  const thickness = (flags.thickness ?? 'thin') as ThicknessId
  if (!(thickness in THICKNESS)) fail(`unknown thickness "${thickness}"`)
  const orientation = (flags.orientation ?? 'portrait') as Orientation
  if (orientation !== 'portrait' && orientation !== 'landscape') {
    fail(`unknown orientation "${orientation}"`)
  }

  const out = flags.out
  const format = (flags.format ?? (out?.endsWith('.svg') ? 'svg' : 'pdf')).toLowerCase()
  if (format !== 'pdf' && format !== 'svg') fail(`unknown format "${format}"`)

  const config: PaperConfig = {
    paperType: command as PaperType,
    paperSize: size,
    orientation,
    spacing: resolveSpacing(flags.spacing, 5),
    margin,
    lineColor: color,
    lineThickness: thickness,
  }

  const target = out ?? `paper.${format}`
  if (format === 'svg') {
    const { svg } = renderPaperSvg(config)
    if (target === '-') process.stdout.write(svg + '\n')
    else writeFileSync(target, svg + '\n')
  } else {
    const pages = Number(flags.pages ?? 1)
    const bytes = renderPaperPdf(config, Number.isFinite(pages) ? pages : 1)
    if (target === '-') process.stdout.write(Buffer.from(bytes))
    else writeFileSync(target, bytes)
  }
  if (target !== '-') console.error(`wrote ${target}`)
}

main()
